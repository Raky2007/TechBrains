import React, { useState, useEffect, useCallback, useRef } from 'react';
import { useTeam } from '../layouts/TeamLayout';
import { CountdownTimer } from '../components/CountdownTimer';
import { apiFetch } from '../lib/api';
import { getSocket } from '../lib/socket';
import { Level1AnswerChoice, TeamPrivateState } from '@nexus/shared';
import { AlertCircle, Loader2 } from 'lucide-react';

const OPTIONS: { choice: Level1AnswerChoice; letter: string; label: string; description: string }[] = [
  { choice: 'AI', letter: 'A', label: 'AI Made', description: 'The output is generated by AI.' },
  { choice: 'HUMAN', letter: 'B', label: 'Human Made', description: 'The output is made by a human.' },
  { choice: 'CANT_DEFINE', letter: 'C', label: "Can't Determine", description: "Cannot determine if it's AI- or human-made." }
];

// How long the chosen answer stays highlighted before auto-advancing.
// Presentation-only; the server does not depend on this delay for scoring.
const RESULT_DISPLAY_MS = 950;

export const Level1GamePage: React.FC = () => {
  const { team, gameState, stage, refreshTeam, refreshGameState } = useTeam();

  const [level1State, setLevel1State] = useState<TeamPrivateState['level1'] | null>(null);
  const [selectedChoice, setSelectedChoice] = useState<Level1AnswerChoice | null>(null);
  const [isSubmitting, setIsSubmitting] = useState<boolean>(false);
  // Once answered/timed-out we lock input and auto-advance. `feedback` colours the
  // chosen option: green = correct, red = wrong, yellow = "Can't Determine".
  const [isResolved, setIsResolved] = useState<boolean>(false);
  const [feedback, setFeedback] = useState<{ choice: Level1AnswerChoice; is_correct: boolean } | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [isLoading, setIsLoading] = useState<boolean>(true);

  const advanceTimer = useRef<ReturnType<typeof setTimeout> | null>(null);
  const isResolvingRef = useRef<boolean>(false);

  const loadProgress = useCallback(async () => {
    try {
      const res = await apiFetch<TeamPrivateState>('/api/game/team-state');
      setLevel1State(res.level1 || null);
    } catch (err: any) {
      console.error('Failed to load team progress:', err);
    } finally {
      setIsLoading(false);
    }
  }, []);

  const advanceToNext = useCallback(async () => {
    setIsResolved(false);
    setFeedback(null);
    setSelectedChoice(null);
    setError(null);
    isResolvingRef.current = false;
    await loadProgress();
  }, [loadProgress]);

  useEffect(() => {
    loadProgress();
    const socket = getSocket();
    const handleRoundEnded = () => {
      refreshGameState();
      loadProgress();
    };
    socket.on('round:ended', handleRoundEnded);
    socket.on('game:state_changed', handleRoundEnded);
    return () => {
      socket.off('round:ended', handleRoundEnded);
      socket.off('game:state_changed', handleRoundEnded);
      if (advanceTimer.current) clearTimeout(advanceTimer.current);
    };
  }, [loadProgress, refreshGameState]);

  const currentQ = level1State?.current_question;
  const isCompleted = level1State?.is_completed || false;
  const isRoundEnded = gameState?.status === 'level1_ended';
  const isLevel2Started = gameState?.status === 'level2_active' || gameState?.status === 'level2_paused' || gameState?.status === 'level2_ended';

  const scheduleAdvance = useCallback(() => {
    if (advanceTimer.current) clearTimeout(advanceTimer.current);
    advanceTimer.current = setTimeout(() => {
      advanceToNext();
    }, RESULT_DISPLAY_MS);
  }, [advanceToNext]);

  const handleSubmitAnswer = useCallback(
    async (choice: Level1AnswerChoice) => {
      if (!currentQ || isSubmitting || isResolved) return;
      setSelectedChoice(choice);
      setIsSubmitting(true);
      setError(null);
      try {
        const res = await apiFetch<{ is_correct: boolean }>('/api/game/level1/answer', {
          method: 'POST',
          body: JSON.stringify({ question_id: currentQ.id, selected_answer: choice })
        });
        setFeedback({ choice, is_correct: res.is_correct });
        setIsResolved(true);
        await refreshTeam();
        scheduleAdvance();
      } catch (err: any) {
        const msg = err?.message || '';
        // Server-authoritative timeout / duplicate at the deadline → just advance.
        if (/time is up|timed out|already submitted/i.test(msg)) {
          setIsResolved(true);
          scheduleAdvance();
        } else {
          setError(msg || 'Failed to submit answer.');
          setIsSubmitting(false);
        }
        return;
      }
      setIsSubmitting(false);
    },
    [currentQ, isSubmitting, isResolved, refreshTeam, scheduleAdvance]
  );

  // Keyboard shortcuts: A/B/C (or 1/2/3) submit the matching answer.
  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if (isSubmitting || isResolved || !currentQ) return;
      const key = e.key.toUpperCase();
      if (key === 'A' || key === '1') handleSubmitAnswer('AI');
      if (key === 'B' || key === '2') handleSubmitAnswer('HUMAN');
      if (key === 'C' || key === '3') handleSubmitAnswer('CANT_DEFINE');
    };
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [isSubmitting, isResolved, currentQ, handleSubmitAnswer]);

  // Per-question server-authoritative timeout → advance without scoring.
  const handleTimeout = useCallback(() => {
    if (isResolvingRef.current || isResolved || isSubmitting) return;
    isResolvingRef.current = true;
    setIsResolved(true);
    scheduleAdvance();
  }, [isResolved, isSubmitting, scheduleAdvance]);

  if (isLoading) {
    return (
      <div className="flex flex-col items-center justify-center min-h-[50vh] gap-3 font-mono text-[#737373] text-sm">
        <Loader2 className="w-7 h-7 animate-spin text-[#171717]" />
        <span>Loading questions…</span>
      </div>
    );
  }

  // Completion / round-ended state (not part of the question sketch — kept minimal).
  const isFinished = !currentQ || isCompleted || isRoundEnded || isLevel2Started || stage === 'round1_done' || stage === 'round2' || stage === 'not_qualified' || stage === 'result';
  if (isFinished && !isResolved) {
    return (
      <div className="flex-1 flex flex-col justify-center max-w-xl mx-auto w-full space-y-6 py-6">
        <p className="text-lg sm:text-xl text-[#171717] leading-relaxed text-center">
          Congratulations,{' '}
          <span className="font-heading font-bold text-[#B34400]">{team?.team_name}</span>, on
          completing Round 1 successfully with the score of
        </p>

        <div className="text-center">
          <div className="inline-block px-8 py-4 rounded-2xl border border-[#E5E5E5] bg-[#F5F5F2]">
            <div className="text-5xl font-heading font-bold font-mono text-[#171717] leading-none">
              {team?.level1_score ?? 0}
              <span className="text-xl text-[#737373] font-normal"> / 30 pts</span>
            </div>
          </div>
        </div>

        <p className="text-sm font-heading font-semibold text-[#171717] text-center">
          Wait until the admin starts Round 2.
        </p>

        <div className="pt-5 border-t border-[#E5E5E5] space-y-2.5">
          <h2 className="font-heading font-bold text-sm text-[#171717]">Rules of Round 2</h2>
          <ul className="space-y-1.5">
            {[
              'Two questions — both are mandatory.',
              'Spend your team’s credits to unlock investigation clues.',
              'Study the case, then submit your final answers before Round 2 ends.'
            ].map((rule) => (
              <li key={rule} className="flex items-start gap-2.5 text-xs text-[#525252] leading-relaxed">
                <span className="mt-2 h-px w-3 bg-[#A3A3A3] shrink-0" aria-hidden="true" />
                <span>{rule}</span>
              </li>
            ))}
          </ul>
        </div>
      </div>
    );
  }

  if (!currentQ) return null;

  const inputsLocked = isSubmitting || isResolved;

  return (
    <div className="max-w-4xl mx-auto space-y-5">
      {/* Title + Round 1 score + team */}
      <div className="flex flex-wrap items-center justify-between gap-3 pb-4 border-b border-[#E5E5E5]">
        <h1 className="text-lg sm:text-xl font-heading font-bold tracking-tight text-[#171717]">
          Round 1: AI vs Human
        </h1>
        <div className="flex items-center gap-5 flex-wrap font-mono text-xs text-[#171717]">
          <span>Round 1 Score: <strong className="font-bold">{team?.level1_score ?? 0}</strong> / 30 pts</span>
          <span>Team: <strong className="font-bold">{team?.team_name}</strong></span>
        </div>
      </div>

      {/* Question label + timer */}
      <div className="flex items-center justify-between gap-3">
        <span className="text-sm font-heading font-bold uppercase tracking-wider text-[#171717]">
          Question {currentQ.question_order}
        </span>
        <CountdownTimer
          deadlineAt={currentQ.deadline_at || null}
          isPaused={inputsLocked}
          remainingSeconds={currentQ.time_limit_seconds || 0}
          onExpire={handleTimeout}
        />
      </div>

      {/* Stimulus box */}
      <div className="bg-[#FFFFFF] border border-[#E5E5E5] rounded-2xl p-6 sm:p-8 shadow-sm space-y-4 min-h-[200px] flex flex-col justify-center">
        <h2 className="text-lg sm:text-xl font-heading font-bold text-[#171717]">{currentQ.title}</h2>
        {currentQ.prompt && (
          <p className="text-sm text-[#525252] leading-relaxed whitespace-pre-wrap font-body">{currentQ.prompt}</p>
        )}
        {currentQ.media_path && (
          <div className="rounded-xl overflow-hidden border border-[#E5E5E5] bg-[#F5F5F2] max-h-96 flex items-center justify-center p-2">
            {currentQ.content_type === 'image' && (
              <img src={currentQ.media_path} alt={currentQ.title} className="max-h-96 w-full object-contain rounded-lg" />
            )}
            {currentQ.content_type === 'video' && (
              <video src={currentQ.media_path} controls className="max-h-96 w-full object-contain rounded-lg" />
            )}
          </div>
        )}
      </div>

      {/* Answer options, side by side — clicking submits immediately.
          Chosen option colours: green = correct, red = wrong, yellow = Can't Determine. */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
        {OPTIONS.map((opt) => {
          const isChosen = selectedChoice === opt.choice;
          let stateClass = 'bg-[#FFFFFF] border-[#E5E5E5] hover:border-[#171717]';
          if (feedback && isChosen) {
            if (opt.choice === 'CANT_DEFINE') stateClass = 'bg-[#FFC928]/25 border-[#E0AD0E]';
            else if (feedback.is_correct) stateClass = 'bg-[#18794E]/15 border-[#18794E]';
            else stateClass = 'bg-[#B42318]/10 border-[#B42318]';
          } else if (inputsLocked && isChosen) {
            stateClass = 'bg-[#FFC928] border-[#171717] shadow-xs';
          } else if (inputsLocked) {
            stateClass = 'bg-[#FFFFFF] border-[#E5E5E5] opacity-50';
          }
          return (
            <button
              key={opt.choice}
              type="button"
              disabled={inputsLocked}
              onClick={() => handleSubmitAnswer(opt.choice)}
              className={`p-4 rounded-xl border text-left flex flex-col gap-1 transition-all cursor-pointer disabled:cursor-not-allowed ${stateClass}`}
            >
              <span className="font-mono font-bold text-base text-[#171717]">{opt.letter}</span>
              <span className="font-heading font-bold text-sm text-[#171717]">{opt.label}</span>
              <span className="text-xs text-[#737373] leading-relaxed">{opt.description}</span>
            </button>
          );
        })}
      </div>

      {error && (
        <div className="p-3.5 rounded-xl bg-[#B42318]/5 border border-[#B42318]/20 text-[#B42318] text-xs flex items-center gap-2">
          <AlertCircle className="w-4 h-4 shrink-0" />
          <span>{error}</span>
        </div>
      )}
    </div>
  );
};
